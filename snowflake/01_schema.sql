CREATE DATABASE IF NOT EXISTS SENTINEL;
CREATE SCHEMA IF NOT EXISTS SENTINEL.RISK;
CREATE WAREHOUSE IF NOT EXISTS SENTINEL_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;

USE DATABASE SENTINEL;
USE SCHEMA RISK;
USE WAREHOUSE SENTINEL_WH;

CREATE OR REPLACE TABLE CUSTOMERS (
  CUSTOMER_ID STRING,
  NAME STRING,
  TYPE STRING,
  PAN STRING,
  CITY STRING,
  KYC_STATUS STRING,
  PEP BOOLEAN,
  RISK_RATING STRING,
  OCCUPATION STRING,
  ONBOARDING_DATE DATE
);

CREATE OR REPLACE TABLE ACCOUNTS (
  ACCOUNT_ID STRING,
  CUSTOMER_ID STRING,
  PRODUCT STRING,
  IFSC STRING,
  OPENED_ON DATE,
  BALANCE_INR NUMBER(18,2),
  STATUS STRING
);

CREATE OR REPLACE TABLE TRANSACTIONS (
  TXN_ID STRING,
  TXN_TS TIMESTAMP_TZ,
  ACCOUNT_ID STRING,
  CUSTOMER_ID STRING,
  COUNTERPARTY STRING,
  CHANNEL STRING,
  TXN_TYPE STRING,
  AMOUNT_INR NUMBER(18,2),
  CITY STRING,
  IS_FRAUD BOOLEAN,
  TYPOLOGY STRING,
  NARRATIVE STRING
);

CREATE OR REPLACE TABLE ALERTS (
  ALERT_ID STRING,
  ALERT_TS TIMESTAMP_TZ,
  CUSTOMER_ID STRING,
  ACCOUNT_ID STRING,
  TITLE STRING,
  TYPOLOGY STRING,
  SCORE NUMBER(5,2),
  STATUS STRING,
  CASE_ID STRING,
  EXPLANATION STRING
);

CREATE OR REPLACE TABLE CASES (
  CASE_ID STRING,
  TITLE STRING,
  STATUS STRING,
  OWNER STRING,
  OPENED_ON DATE,
  TYPOLOGY STRING,
  SEVERITY STRING,
  SUMMARY STRING
);

CREATE OR REPLACE TABLE CALL_TRANSCRIPTS (
  CALL_ID STRING,
  CUSTOMER_ID STRING,
  CALL_TS TIMESTAMP_TZ,
  TRANSCRIPT_TEXT STRING
);

CREATE OR REPLACE TABLE REG_DOCS (
  DOC_ID STRING,
  TITLE STRING,
  SOURCE STRING,
  CLAUSE STRING,
  TOPIC STRING,
  EXCERPT STRING
);

CREATE OR REPLACE TABLE LIQUIDITY_DAILY (
  AS_OF DATE,
  LCR_PCT FLOAT,
  NSFR_PCT FLOAT,
  HQLA_INR_CR FLOAT,
  WHOLESALE_RUNOFF_INR_CR FLOAT,
  BUFFER_DAYS NUMBER
);

CREATE OR REPLACE TABLE CREDIT_EXPOSURES (
  CUSTOMER_ID STRING,
  CUSTOMER_NAME STRING,
  EXPOSURE_INR NUMBER(18,2),
  SECTOR STRING
);

CREATE OR REPLACE TABLE COPILOT_AUDIT (
  AUDIT_ID STRING,
  ASKED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
  USER_NAME STRING,
  QUESTION STRING,
  ANSWER STRING,
  CONFIDENCE STRING,
  CITATIONS STRING,
  SQL_TEXT STRING
);

-- Enable change tracking for Cortex Search
ALTER TABLE CALL_TRANSCRIPTS SET CHANGE_TRACKING = TRUE;
ALTER TABLE REG_DOCS SET CHANGE_TRACKING = TRUE;

