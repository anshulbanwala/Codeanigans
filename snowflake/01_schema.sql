CREATE OR REPLACE CORTEX SEARCH SERVICE REG_DOC_SEARCH
  ON EXCERPT
  ATTRIBUTES TITLE, TOPIC, CLAUSE, SOURCE
  WAREHOUSE = SENTINEL_WH
  TARGET_LAG = '1 hour'
  AS (SELECT DOC_ID, TITLE, TOPIC, CLAUSE, SOURCE, EXCERPT FROM REG_DOCS);

CREATE OR REPLACE CORTEX SEARCH SERVICE CALL_SEARCH
  ON TRANSCRIPT_TEXT
  ATTRIBUTES CUSTOMER_ID, CALL_ID
  WAREHOUSE = SENTINEL_WH
  TARGET_LAG = '1 hour'
  AS (SELECT CALL_ID, CUSTOMER_ID, CALL_TS, TRANSCRIPT_TEXT FROM CALL_TRANSCRIPTS);

